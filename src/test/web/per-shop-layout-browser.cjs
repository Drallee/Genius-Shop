const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require(path.resolve(__dirname, '../../../target/rendering-tools/node_modules/playwright'));
const { createDraftPreviewServer } = require('./draft-preview-server.cjs');
const { report } = require('./sales-preview-server.cjs');

(async () => {
    const server = createDraftPreviewServer();
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const browser = await chromium.launch({ channel: 'chrome', headless: true });
    try {
        const mobile = process.argv.includes('--mobile');
        const page = await browser.newPage({ viewport: mobile ? { width: 390, height: 844 } : { width: 1365, height: 1000 } });
        page.setDefaultTimeout(8000);
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        await page.route('https://**/*', route => route.abort());
        await page.route('**/api/sales-analytics?**', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify(report(new URL(route.request().url()).searchParams)) }));
        await page.addInitScript(() => {
            localStorage.setItem('autoSaveEnabled', 'false');
            localStorage.setItem('geniusshop:tutorial:v1:preview', JSON.stringify({ firstRunHandled: true, autoNewFeatures: false, sections: {} }));
        });
        await page.goto(`http://127.0.0.1:${server.address().port}`, { waitUntil: 'domcontentloaded' });
        await page.waitForFunction(() => !getEditorState('isLoadingFiles') && Object.keys(allShops).length > 0);
        const state = server.draftState;
        const other = 'gui-name: Other\nrows: 3\nitems: [{material: STONE, price: 1, slot: 0}]\n';
        state.live['shops/other.yml'] = other;
        state.workspace['shops/other.yml'] = other;
        await page.evaluate(async () => { await loadAllFiles(true); switchTab('guisettings'); GuiLayout.setRows(6); await saveCurrentTabChanges(true); });
        await page.locator('#gui-layout-scope').selectOption('blocks.yml');
        await page.evaluate(() => GuiLayout.setRows(3));
        assert.equal(await page.locator('#gui-layout-preview > button').count(), 27);
        await page.getByRole('button', { name: 'FILLER', exact: true }).click();
        await page.locator('#gui-layout-preview > button').nth(0).click();
        assert.equal(await page.locator('#gui-layout-preview > button').nth(0).evaluate(node => node.classList.contains('layout-filler')), true);
        await page.getByRole('button', { name: 'BUTTONS', exact: true }).click();
        await page.locator('#gui-layout-preview > button').nth(0).click();
        assert.equal(await page.evaluate(() => currentShopSettings.layout.buttons.searchButton.slot), 0);
        await page.getByRole('button', { name: 'ITEM AREA', exact: true }).click();
        await page.locator('#gui-layout-preview > button').nth(18).click();
        assert.equal(await page.locator('#gui-layout-preview > button').nth(18).evaluate(node => node.classList.contains('layout-content')), true);
        await page.getByRole('button', { name: 'EDIT FILLER', exact: true }).click();
        await page.locator('#enabled').check();
        await page.locator('#edit-modal button[onclick="saveEditModal()"]').click();
        assert.ok(await page.locator('#gui-layout-preview img[alt="yellow_stained_glass_pane"]').count() > 0);
        assert.equal(await page.locator('#gui-layout-preview img[alt="gray_dye"]').count(), 1);
        assert.equal(await page.locator('#gui-layout-preview img[alt="lime_dye"]').count(), 1);
        const sharedBefore = state.workspace['menus/gui-settings.yml'];
        await page.locator('button[onclick="manualSave()"]').click();
        await page.locator('#save-confirmation-modal').waitFor({ state: 'visible' });
        assert.ok(await page.locator('#save-confirmation-content details.draft-file').count() > 0);
        assert.equal(await page.locator('#save-confirmation-content details').first().evaluate(node => node.open), true);
        assert.equal(await page.locator('#save-confirmation-content .change-comparison').first().isVisible(), true);
        await page.locator('#save-confirmation-modal button[onclick="confirmSave()"]').click();
        await page.waitForFunction(() => !isSaving);
        assert.equal(state.workspace['menus/gui-settings.yml'], sharedBefore, 'Shop layout saves must not change shared defaults');
        assert.match(state.workspace['shops/blocks.yml'], /layout:/);
        await page.locator('#gui-layout-scope').selectOption('other.yml');
        await page.evaluate(async () => { GuiLayout.setRows(4); await saveCurrentTabChanges(true); });
        assert.equal(await page.locator('#gui-layout-preview > button').count(), 36);
        await page.locator('#gui-layout-scope').selectOption('blocks.yml');
        assert.equal(await page.locator('#gui-layout-preview > button').count(), 27);
        await page.evaluate(() => switchTab('shop'));
        assert.equal(await page.locator('#shop-rows-input').isVisible(), false);
        assert.equal(await page.locator('#shop-layout-override').isVisible(), true);
        assert.equal(await page.locator('#preview-grid > .gui-slot').count(), 27);
        assert.ok(await page.locator('#preview-grid .layout-reserved img').count() > 0);
        await page.reload({ waitUntil: 'domcontentloaded' });
        await page.waitForFunction(() => !getEditorState('isLoadingFiles') && currentShopSettings.layout?.rows === 3);
        await page.evaluate(() => { switchTab('guisettings'); GuiLayout.selectScope('other.yml'); });
        assert.equal(await page.locator('#gui-layout-preview > button').count(), 36);
        await page.screenshot({ path: path.resolve(__dirname, `../../../target/per-shop-layout-${mobile ? 'mobile' : 'desktop'}.png`), fullPage: true });
        await page.evaluate(() => switchTab('salesanalytics'));
        await page.locator('#sales-results').waitFor({ state: 'visible' });
        await page.locator('#custom-sales-shop .custom-select-trigger').click();
        await page.locator('#custom-sales-shop .custom-select-option').filter({ hasText: /^blocks$/ }).click();
        await page.locator('#sales-results').waitFor({ state: 'visible' });
        await page.locator('#custom-sales-item .custom-select-trigger').click();
        await page.locator('#custom-sales-item .custom-select-option').filter({ hasText: /^stone$/ }).click();
        await page.waitForFunction(() => document.querySelector('#sales-filters').getAttribute('aria-busy') === 'false');
        await page.locator('#sales-price-content').waitFor({ state: 'visible' });
        if (!mobile) {
            const bottoms = await page.locator('#sales-filters input, #sales-filters .custom-select-trigger, #sales-filters button').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().bottom));
            assert.ok(Math.max(...bottoms) - Math.min(...bottoms) < 3, 'Sales refresh must align with filters: ' + JSON.stringify(bottoms));
        }
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2), false);
        assert.deepEqual(errors, []);
        console.log('PASS per-shop layout painting, isolated saves, previews, save review, and Sales filters ' + (mobile ? 'mobile' : 'desktop'));
    } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exitCode = 1; });
