const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require(path.resolve(__dirname, '../../../target/rendering-tools/node_modules/playwright'));
const { createDraftPreviewServer } = require('./draft-preview-server.cjs');

(async () => {
    const server = createDraftPreviewServer();
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const browser = await chromium.launch({ channel: 'chrome', headless: true });
    try {
        const mobile = process.argv.includes('--mobile');
        const page = await browser.newPage({ viewport: mobile ? { width: 390, height: 844 } : { width: 1365, height: 950 } });
        page.setDefaultTimeout(8000);
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        await page.route('https://**/*', route => route.abort());
        await page.addInitScript(() => {
            localStorage.setItem('autoSaveEnabled', 'false');
            localStorage.setItem('geniusshop:tutorial:v1:preview', JSON.stringify({ firstRunHandled: true, autoNewFeatures: false, sections: {} }));
        });
        await page.goto(`http://127.0.0.1:${server.address().port}`, { waitUntil: 'domcontentloaded' });
        await page.waitForFunction(() => !getEditorState('isLoadingFiles') && typeof EditorShortcuts !== 'undefined' && !document.getElementById('editor-shortcuts-button').disabled);
        await page.evaluate(() => switchTab('shop'));
        assert.equal(await page.locator('#shop-rows-input').isVisible(), true);
        assert.equal(await page.locator('#shop-layout-override').isVisible(), false);
        assert.equal(await page.locator('#quick-tips-list').count(), 0);
        await page.locator('#shop-rows-input').fill('5');
        await page.locator('#shop-rows-input').dispatchEvent('change');
        assert.equal(await page.evaluate(() => currentShopSettings.rows), 5);
        await page.evaluate(() => { GuiLayout.selectScope(currentShopFile); switchTab('guisettings'); GuiLayout.setRows(5); });
        const headingBottom = await page.getByRole('heading', { name: 'Shop layout', exact: true }).evaluate(node => node.getBoundingClientRect().bottom);
        assert.ok(await page.locator('.gui-layout-scope').evaluate(node => node.getBoundingClientRect().top) >= headingBottom);
        await page.getByRole('button', { name: 'EDIT FILLER', exact: true }).click();
        await page.locator('#enabled').check();
        await page.locator('#edit-modal button[onclick="saveEditModal()"]').click();
        await page.getByRole('button', { name: 'EMPTY / AIR', exact: true }).click();
        for (const slot of [42,43,44]) await page.locator('#gui-layout-preview > button').nth(slot).click();
        assert.deepEqual(await page.evaluate(() => currentShopSettings.layout.emptySlots), [42,43,44]);
        for (const slot of [42,43,44]) assert.equal(await page.locator('#gui-layout-preview > button').nth(slot).locator('img').count(), 0);
        await page.getByRole('button', { name: 'FILLER', exact: true }).click();
        await page.locator('#gui-layout-preview > button').nth(35).click();
        assert.equal(await page.locator('#gui-layout-preview > button').nth(35).locator('img[alt="yellow_stained_glass_pane"]').count(), 1);
        await page.locator('#gui-empty-area').selectOption('filler');
        const vacant = await page.evaluate(() => GuiLayout.current().contentSlots.find(slot => !items.some(item => item.slot === GuiLayout.current().contentSlots.indexOf(slot))));
        assert.notEqual(vacant, undefined);
        assert.equal(await page.locator('#gui-layout-preview > button').nth(vacant).locator('img[alt="yellow_stained_glass_pane"]').count(), 1);
        await page.locator('#gui-empty-area').selectOption('item');
        await page.getByRole('button', { name: 'EDIT UNUSED-SLOT ITEM', exact: true }).click();
        await page.locator('#material').fill('BLACK_STAINED_GLASS_PANE');
        await page.locator('#edit-modal button[onclick="saveEditModal()"]').click();
        assert.equal(await page.locator('#gui-layout-preview > button').nth(vacant).locator('img[alt="black_stained_glass_pane"]').count(), 1);
        await page.evaluate(async () => { await saveCurrentTabChanges(true); switchTab('shop'); });
        assert.equal(await page.locator('#shop-rows-input').isVisible(), false);
        assert.equal(await page.locator('#shop-layout-override').isVisible(), true);
        for (const slot of [42,43,44]) assert.equal(await page.locator('#preview-grid > div').nth(slot).locator('img').count(), 0);
        await page.evaluate(() => { items[0].price = 4321; unsavedChanges = []; });
        await page.locator('button[onclick="manualSave()"]').click();
        const review = page.locator('#save-confirmation-content');
        assert.ok(await review.locator('.draft-save-current details[open]').count() > 0);
        assert.match(await review.locator('.draft-after').first().textContent(), /4321/);
        assert.doesNotMatch(await review.locator('.draft-before').first().textContent(), /4321/);
        await page.keyboard.press('Escape');
        await page.locator('#save-confirmation-modal').waitFor({ state: 'hidden' });
        const writesBefore = server.draftState.requests.length;
        await page.locator('#preview-title-input').focus();
        await page.keyboard.press('Control+s');
        await page.waitForFunction(() => !isSaving);
        assert.ok(server.draftState.requests.length > writesBefore, 'Ctrl+S saves even from a focused input');
        assert.match(server.draftState.workspace['shops/blocks.yml'], /price: 4321/);
        assert.equal(server.draftState.publishes, 0);
        await page.keyboard.press('Control+Shift+s');
        await page.locator('#draft-review').waitFor({ state: 'visible' });
        assert.equal(server.draftState.publishes, 0, 'Publish shortcut must not bypass confirmation');
        await page.locator('#draft-review button[aria-label="Close review"]').click();
        await page.keyboard.press('Control+h');
        await page.locator('#activity-log-modal').waitFor({ state: 'visible' });
        await page.keyboard.press('Escape');
        await page.locator('#activity-log-modal').waitFor({ state: 'hidden' });
        await page.keyboard.press('Control+r');
        await page.locator('#confirm-modal').waitFor({ state: 'visible' });
        assert.match(await page.locator('#confirm-modal-content').textContent(), /reload/i);
        await page.locator('#confirm-modal button[onclick="closeConfirmModal(false)"]').click();
        await page.locator('#confirm-modal').waitFor({ state: 'hidden' });
        await page.keyboard.press('Control+Alt+ArrowRight');
        assert.equal(await page.evaluate(() => currentTab), 'purchase');
        await page.keyboard.press('Control+Alt+ArrowLeft');
        assert.equal(await page.evaluate(() => currentTab), 'shop');
        if (mobile) await page.locator('#navigation-toggle').click();
        await page.locator('#editor-shortcuts-button').click();
        await page.locator('#editor-shortcuts').waitFor({ state: 'visible' });
        assert.equal(await page.locator('#editor-shortcuts .shortcut-row').count(), 8);
        await page.screenshot({ path: path.resolve(__dirname, `../../../target/shortcuts-${mobile ? 'mobile' : 'desktop'}.png`) });
        await page.keyboard.press('Control+/');
        await page.locator('#editor-shortcuts').waitFor({ state: 'hidden' });
        await page.keyboard.press('Control+/');
        await page.locator('#editor-shortcuts').waitFor({ state: 'visible' });
        await page.keyboard.press('Escape');
        await page.reload({ waitUntil: 'domcontentloaded' });
        await page.waitForFunction(() => !getEditorState('isLoadingFiles') && currentShopSettings.layout?.emptySlots?.length === 3);
        assert.deepEqual(await page.evaluate(() => currentShopSettings.layout.emptySlots), [42,43,44]);
        assert.equal(await page.evaluate(() => currentShopSettings.layout.emptyItem.material), 'BLACK_STAINED_GLASS_PANE');
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2), false);
        assert.deepEqual(errors, []);
        console.log('PASS explicit air, unused item placeholders, rows override, real draft diffs, and shortcuts ' + (mobile ? 'mobile' : 'desktop'));
    } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exitCode = 1; });
